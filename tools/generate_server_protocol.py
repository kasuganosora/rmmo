#!/usr/bin/env python3
"""Generate Godot descriptors for the checked-in game.proto (no runtime deps)."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]

def generate(source: Path) -> str:
    raw = source.read_bytes()
    text = re.sub(r"//[^\n]*", "", raw.decode())
    schema = {}
    for match in re.finditer(r"\bmessage\s+(\w+)\s*\{", text):
        start = match.end()
        depth, end = 1, start
        while depth:
            depth += (text[end] == "{") - (text[end] == "}")
            end += 1
        fields = {}
        for field in re.finditer(r"\b(repeated\s+)?(\w+)\s+(\w+)\s*=\s*(\d+)\s*;", text[start:end-1]):
            fields[int(field[4])] = [field[3], field[2], bool(field[1])]
        schema[match[1]] = fields
    lines = ["extends RefCounted", "# Generated by tools/generate_server_protocol.py; do not edit.",
             f'const SOURCE_SHA256="{hashlib.sha256(raw).hexdigest()}"', "const SCHEMA={"]
    for name, fields in schema.items():
        lines.append(f'\t"{name}":{{')
        for number, spec in fields.items():
            lines.append(f'\t\t{number}:{json.dumps(spec, ensure_ascii=False)},')
        lines.append("\t},")
    return "\n".join(lines + ["}", ""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "scripts/net/protocol/schema.gd"
    output = generate(ROOT / "scripts/net/protocol/game.proto")
    if args.check:
        if target.read_text() != output:
            raise SystemExit("Protocol descriptors are stale; regenerate them")
    else:
        target.write_text(output)
