#!/usr/bin/env python3
"""Generate the stable MockServer facade from domain-owned declarations.

Only declarations marked @server-api, @server-state or @server-constant are
exported. Modules keep their implementation and storage; the facade forwards
calls and property access without copying mutable state.
"""
import argparse
from dataclasses import dataclass
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "scripts/net/mock_server_api.gd"
MARKER = re.compile(r"^## @server-(api|state|constant)(?: (\w+))?\n", re.M)


@dataclass(frozen=True)
class Export:
    module: str
    kind: str
    name: str
    target: str
    arguments: str = ""
    result: str = ""


def split_arguments(arguments: str) -> list[str]:
    """Split parameters, respecting containers and quoted default values."""
    parts, start, depth, quote, escaped = [], 0, 0, "", False
    for index, char in enumerate(arguments):
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = ""
        elif char in "\"'":
            quote = char
        elif char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(arguments[start:index].strip())
            start = index + 1
    if arguments[start:].strip():
        parts.append(arguments[start:].strip())
    return parts


def exports() -> list[Export]:
    rows, seen = [], set()
    for path in sorted((ROOT / "scripts/net/server").glob("*_module.gd")):
        source = path.read_text(encoding="utf-8")
        for marker in MARKER.finditer(source):
            kind, alias = marker.groups()
            declaration = source[marker.end():]
            if kind == "api":
                match = re.match(r"func (\w+)\(([\s\S]*?)\)\s*(?:->\s*([^:\n]+))?\s*:\n", declaration)
                if not match:
                    raise ValueError(f"{path}: @server-api must precede a function")
                target, arguments, result = match.groups()
                row = Export(path.stem, kind, alias or target, target,
                             re.sub(r'''("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')|\s+''',
                                    lambda m: m[1] or " ", arguments).strip(),
                             (result or "").strip())
            else:
                keyword = "var" if kind == "state" else "const"
                match = re.match(rf"{keyword} (\w+)(?:\s*:\s*([\w\[\], ]+?))?(?=\s*(?:=|:=|:|\n))", declaration)
                if not match:
                    raise ValueError(f"{path}: @server-{kind} must precede a {keyword}")
                target, result = match.groups()
                row = Export(path.stem, kind, alias or target, target, result=(result or "").strip())
            if row.name in seen:
                raise ValueError(f"Duplicate server export: {row.name}")
            seen.add(row.name)
            rows.append(row)
    return rows


def generate() -> str:
    rows = exports()
    lines = ["extends Node", "## Generated by tools/generate_mock_server_api.py; do not edit.",
             "## Edit @server-* declarations in scripts/net/server/*_module.gd.", "",
             "signal login_finished(ok: bool, message: String)",
             "signal characters_ready(list: Array)",
             "signal character_created(ok: bool, message: String, character: Dictionary)",
             "signal enter_world_ready(ok: bool, message: String, spawn: Dictionary)", ""]
    for module in sorted({row.module for row in rows}):
        lines.append(f'var _{module}_logic = preload("res://scripts/net/server/{module}.gd").new(self)')
    # These two services are used directly by existing world/character adapters.
    lines += ['var facial_expressions = _facial_expression_module_logic',
              'var furniture = preload("res://scripts/net/server/furniture_module.gd").new()', '']
    for row in rows:
        if row.kind == "constant":
            lines.append(f'const {row.name} = preload("res://scripts/net/server/{row.module}.gd").{row.target}')
        elif row.kind == "state":
            kind = f": {row.result}" if row.result else ""
            lines += [f"var {row.name}{kind}:", f"\tget: return _{row.module}_logic.{row.target}",
                      f"\tset(value): _{row.module}_logic.{row.target} = value"]
        else:
            arguments = ", ".join(re.match(r"\w+", part)[0] for part in split_arguments(row.arguments))
            result = f" -> {row.result}" if row.result else ""
            prefix = "" if row.result == "void" else "return "
            lines += [f"func {row.name}({row.arguments}){result}:",
                      f"\t{prefix}_{row.module}_logic.{row.target}({arguments})"]
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            raise SystemExit("MockServer facade is stale; run tools/generate_mock_server_api.py")
    else:
        TARGET.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
